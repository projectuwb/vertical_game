// Hand-written service worker generator (Task 5.1, TECH_SPEC.md §10: "Hand-written
// service worker (no Workbox): precache the built asset manifest at install, cache-first
// for hashed assets, network-first with cache fallback for `index.html`, and a version
// bump that clears old caches on activate"). Runs *after* `vite build` (npm run build's
// pipeline), because the precache list has to be the real hashed filenames Vite just
// produced — nothing before that step knows what they are.
//
//   npm run generate-sw

import { createHash } from 'node:crypto';
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';

const DIST_DIR = resolve(process.cwd(), 'dist');
const SW_FILE_NAME = 'sw.js';

function listFiles(dir: string, base: string): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      out.push(...listFiles(full, base));
    } else if (entry !== SW_FILE_NAME) {
      // Sourcemaps are dev/debugging aids, not needed to play offline, and roughly
      // double precache size for nothing a player ever benefits from — TECH_SPEC.md §8's
      // payload budget is about what actually ships to a phone, not debug artefacts.
      if (entry.endsWith('.map')) continue;
      out.push('/' + relative(base, full).split(/\\/g).join('/'));
    }
  }
  return out;
}

/** A hand-rolled, purpose-built service worker — not templated from a framework, so
 *  the entire cache strategy is readable in one place. `self`/`caches`/`fetch` etc. are
 *  the Service Worker global scope's own ambient APIs; this file runs as a classic
 *  (non-module) worker script, never bundled or type-checked as part of the app itself. */
function renderServiceWorker(cacheVersion: string, precacheUrls: readonly string[]): string {
  const cacheName = `inkfall-${cacheVersion}`;
  return `// Generated by src/build/generateServiceWorker.ts — do not edit by hand.
const CACHE_NAME = ${JSON.stringify(cacheName)};
const PRECACHE_URLS = ${JSON.stringify(precacheUrls, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE_NAME)
      .then((cache) => cache.addAll(PRECACHE_URLS))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const url = new URL(event.request.url);
  // Never intercept cross-origin requests — offline-first (TECH_SPEC.md §3) applies to
  // this app's own assets, not to acting as a proxy for anything else.
  if (url.origin !== self.location.origin) return;
  if (event.request.method !== 'GET') return;

  const isNavigation = event.request.mode === 'navigate' || url.pathname === '/' || url.pathname === '/index.html';

  if (isNavigation) {
    // Network-first with cache fallback for the document itself, so a real deploy is
    // always preferred when reachable, and the last cached shell still loads offline.
    event.respondWith(
      fetch(event.request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(event.request, copy));
          return response;
        })
        .catch(() => caches.match('/index.html').then((cached) => cached ?? caches.match(event.request))),
    );
    return;
  }

  // Cache-first for hashed, content-addressed build assets — they never change under a
  // given URL, so there is nothing to revalidate against the network.
  event.respondWith(caches.match(event.request).then((cached) => cached ?? fetch(event.request)));
});
`;
}

function main(): void {
  const files = listFiles(DIST_DIR, DIST_DIR);
  const precacheUrls = ['/', ...files].sort();
  const cacheVersion = createHash('sha256').update(precacheUrls.join('\n')).digest('hex').slice(0, 12);

  const swSource = renderServiceWorker(cacheVersion, precacheUrls);
  writeFileSync(resolve(DIST_DIR, SW_FILE_NAME), swSource);
  console.log(`Generated ${SW_FILE_NAME} — ${precacheUrls.length} precached URL(s), cache ${cacheVersion}.`);
}

main();
